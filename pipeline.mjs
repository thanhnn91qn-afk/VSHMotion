// ---- helpers for the scene styles ----

export const esc = (s) =>
  String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
export const fileUrl = (p) => pathToFileURL(p).href;
export const photoUrl = (name) => fileUrl(join(ROOT, "assets", "photos", name));
export const logoUrl = () => fileUrl(join(ROOT, "assets", "logo.png"));

/**
 * `scene.focus` ("x% y%") keeps the subject in frame when a landscape photo is
 * cropped for a narrower frame - the crop is centred otherwise, and a robot
 * standing at the right edge of the shot simply fell out of its own scene.
 * The Ken Burns zoom heads for the same point.
 */
export const focusAttr = (s) =>
  s.focus && /^\d{1,3}% \d{1,3}%$/.test(s.focus)
    ? ` style="object-position:${s.focus};transform-origin:${s.focus}"`
    : "";

export function parseStat(stat) {
  if (!stat) return null;
  if (/^(19|20)\d{2}$/.test(stat)) return null;
  const m = String(stat).match(/^([\d.]+)(.*)$/);
  if (!m) return null;
  const target = parseInt(m[1].replace(/\./g, ""), 10);
  if (!isFinite(target)) return null;
  return { target, suffix: m[2] ?? "", grouped: m[1].includes(".") };
}

// ---- the run ----

async function tts(text, outWav) {
  // The cache is keyed by scene id, so the text it was made from is kept next
  // to it. Without that, editing a scene's narration silently reused the old
  // recording - a shortened script still came out at its old length.
  const stamp = `${outWav}.txt`;
  if (existsSync(outWav) && !FORCE && existsSync(stamp) &&
      (await readFile(stamp, "utf8")) === text) return;
  const res = await fetch(`${TTS_ENDPOINT}/tts`, {
    method: "POST",
    headers: { "Content-Type": "application/json; charset=utf-8" },
    body: JSON.stringify({ text }),
  });
  if (!res.ok) throw new Error(`TTS ${res.status}`);
  await writeFile(outWav, Buffer.from(await res.arrayBuffer()));
  await writeFile(stamp, text, "utf8");
}

async function durationSec(path) {
  const { stdout } = await exec("ffprobe", [
    "-v", "error", "-show_entries", "format=duration",
    "-of", "default=noprint_wrappers=1:nokey=1", path,
  ]);
  const d = parseFloat(stdout.trim());
  if (!isFinite(d)) throw new Error(`bad duration for ${path}`);
  return d;
}

/**
 * Background music. In order: --no-music or brand.music "none" turns it off;
 * --music=<file> or brand.music (a file under assets/music/) uses that track;
 * otherwise a bed is generated by tools/make-music.py in the mood the content
 * suggests (brand.musicMood overrides). Generation needs Python + numpy - if
 * that is missing the clip is still built, just without music.
 */
async function musicPath(cfg) {
  const m = cfg.brand?.music;
  if (process.argv.includes("--no-music") || m === "none" || m === false) return null;
  if (arg("music")) return arg("music");
  if (m) {
    const p = join(ROOT, "assets", "music", m);
    if (!existsSync(p)) throw new Error(`khong tim thay nhac nen assets/music/${m}`);
    return p;
  }
  const mood = cfg.brand?.musicMood || chooseMood(cfg);
  const out = join(ROOT, "build", "music", `${mood}.wav`);
  if (!existsSync(out)) {
    await mkdir(join(ROOT, "build", "music"), { recursive: true });
    try {
      await exec(process.env.PYTHON || "python",
        [join(ROOT, "tools", "make-music.py"), "--mood", mood, "--out", out]);
    } catch (e) {
      console.log(`[nhac nen] khong sinh duoc (${String(e.message).split("\n")[0]}) - dung khong co nhac`);
      return null;
    }
  }
  console.log(`[nhac nen] tu sinh, tam trang: ${mood}`);
  return out;
}

/** `--scenes=x.json` is looked up as given, then under scenes/. */
function scenesPath(file) {
  if (isAbsolute(file)) return file;
  for (const p of [join(ROOT, file), join(ROOT, "scenes", file)]) if (existsSync(p)) return p;
  throw new Error(`khong tim thay kich ban ${file} (da tim o thu muc goc va scenes/)`);
}

/**
 * fmt: { W, H, styles, stillsDir, defaults: { scenes, name },
 *        minClipSec, statMinMs, stillAtMs }
 */
export async function run(fmt) {
  const { W, H, styles } = fmt;
  const name = arg("name") || fmt.defaults.name;
  // Per-name dirs: scene ids repeat across scripts, and a shared voice cache
  // silently hands one video another video's narration.
  const dirs = {
    voice: join(ROOT, "build", `voice-${name}`),
    clips: join(ROOT, "build", `clips-${name}`),
    stills: join(ROOT, "build", fmt.stillsDir),
    out: resolveOutDir(ROOT),
  };
  const cfg = JSON.parse(await readFile(scenesPath(arg("scenes") || fmt.defaults.scenes), "utf8"));
  // Fill in whatever the script left to "auto" - style, motif, transition -
  // before validation, so the checks see the scene as it will be rendered; and
  // validate before the first TTS call, since a bad style name or a missing
  // photo is not worth finding out about five minutes into a render.
  for (const line of direct(cfg, { portrait: H > W })) console.log(`[dao dien] ${line}`);
  assertScenes(cfg, { styles: Object.keys(styles), root: ROOT });
  for (const d of Object.values(dirs)) await mkdir(d, { recursive: true });

  // A motif seen twice reads as a repeated picture, which is the one thing the
  // photo mapping is careful to avoid - so say so rather than shipping it quietly.
  const usedArt = new Map();
  for (const s of cfg.scenes) {
    const a = s.photo ? null : pickArt(s);
    if (!a) continue;
    if (usedArt.has(a)) console.log(`[warn] hinh ve "${a}" lap lai: ${usedArt.get(a)} va ${s.id}`);
    else usedArt.set(a, s.id);
  }

  const scenes = [];
  for (const s of cfg.scenes) {
    let clipDur = fmt.minClipSec;
    let wav = null;
    if (!STILLS) {
      wav = join(dirs.voice, `${s.id}.wav`);
      process.stdout.write(`[tts]  ${s.id} ... `);
      await tts(s.voice, wav);
      const n = await durationSec(wav);
      clipDur = n + GAP_SEC;
      console.log(`${n.toFixed(2)}s`);
      // list lines and chart bars land on the words that name them
      const items = (s.chart || []).length ? s.chart.map((c) => c.label) : (s.lines || []);
      if (items.length && s.style !== "logo") {
        s.__cues = await phraseCues(exec, wav, s.voice, items, n);
        if (s.__cues) console.log(`[dong bo] ${s.id}: ` +
          s.__cues.map((c) => (c === null ? "-" : (c / 1000).toFixed(2) + "s")).join(", "));
      }
    }
    const parsed = parseStat(s.stat);
    const nLines = (s.lines || []).length;
    scenes.push({
      ...s, wav, clipDur,
      __cfg: {
        clipDurMs: clipDur * 1000,
        zoomOut: s.zoom === "out",
        statRevealMs: Math.max(fmt.statMinMs, clipDur * 1000 * 0.42),
        statTarget: parsed ? parsed.target : null,
        statSuffix: parsed ? parsed.suffix : "",
        statGrouped: parsed ? parsed.grouped : false,
        wordMs: s.wordMs || 190,
        artStartMs: s.artStartMs || 300,
        artStepMs: s.artStepMs || 210,
        artDrawMs: s.artDrawMs || 620,
        lineCues: s.__cues || null,
        lineStartMs: s.lineStartMs || 1000,
        // spread the lines across the narration so each lands with its sentence
        lineMs: s.lineMs || (nLines ? Math.max(900, (clipDur * 1000 - 2200) / nLines) : 1300),
      },
    });
  }

  if (!CHROME) throw new Error("khong tim thay Chrome - dat bien moi truong CHROME_PATH");
  const browser = await puppeteer.launch({
    executablePath: CHROME,
    headless: "new",
    userDataDir: join(tmpdir(), `vshmotion-${name}-${process.pid}`),
    args: ["--no-sandbox", "--disable-gpu", "--hide-scrollbars", "--no-first-run",
      "--no-default-browser-check", "--disable-extensions",
      "--disable-background-networking", "--disable-sync", "--force-device-scale-factor=1"],
    defaultViewport: { width: W, height: H },
    protocolTimeout: 300000,
  });
  try {
    const page = await browser.newPage();
    for (const s of scenes) {
      const render = styles[s.style];
      if (!render) throw new Error(`unknown style: ${s.style}`);
      const htmlPath = join(dirs.clips, `_${s.id}.html`);
      await writeFile(htmlPath, render(s), "utf8");
      await page.goto(fileUrl(htmlPath), { waitUntil: "load" });
      await page.evaluate(() => document.fonts.ready);

      if (STILLS) {
        // Late enough that every reveal has settled - including the stat block,
        // which only starts at 42% of the clip and then counts up for ~0.7s.
        await page.evaluate((t) => window.__frame(t), fmt.stillAtMs);
        // Keyed by scene id, not style: several scenes share a style and would
        // otherwise overwrite each other, hiding the variants worth checking.
        await page.screenshot({ path: join(dirs.stills, `${s.id}-${s.style}.png`), type: "png" });
        console.log(`[still] ${s.id} ${s.style}`);
        continue;
      }

      const frames = Math.round(s.clipDur * FPS);
      s.frames = frames;
      const out = join(dirs.clips, `${s.id}.mp4`);
      process.stdout.write(`[clip] ${s.id} (${s.style}, ${frames}f) ... `);
      const ff = spawn("ffmpeg", [
        "-y", "-hide_banner", "-loglevel", "error",
        "-f", "image2pipe", "-framerate", String(FPS), "-i", "-",
        "-c:v", "libx264", "-preset", "veryfast", "-crf", "20", "-pix_fmt", "yuv420p",
        "-r", String(FPS), out,
      ]);
      const done = new Promise((res, rej) => {
        ff.on("close", (c) => (c === 0 ? res() : rej(new Error(`ffmpeg ${c}`))));
        ff.on("error", rej);
      });
      for (let i = 0; i < frames; i++) {
        // preroll: the opening scene starts part-way into its own reveal, so frame 0
        // - the thumbnail a muted autoplay shows - is a real picture, not an empty ground
        await page.evaluate((t) => window.__frame(t), (i / FPS) * 1000 + (s.preroll || 0));
        const buf = await page.screenshot({ type: "jpeg", quality: 92 });
        if (!ff.stdin.write(buf)) await new Promise((r) => ff.stdin.once("drain", r));
      }
      ff.stdin.end();
      await done;
      s.clip = out;
      console.log("ok");
    }
  } finally {
    await browser.close();
  }

  if (STILLS) {
    console.log(`\nStills in ${dirs.stills}`);
    return;
  }

  console.log(NO_TRANS ? "[video] noi canh (khong chuyen canh)" : "[video] noi canh co chuyen canh");
  const { silent, withAudio, joins, cues, loud } = await assemble({
    scenes, fps: FPS, gap: GAP_SEC, exec, root: ROOT, name,
    outDir: dirs.out, base: outBaseName(cfg, name), off: NO_TRANS,
    music: await musicPath(cfg), musicVol: Number(cfg.brand?.musicVolume ?? 0.16),
    sfxOff: process.argv.includes("--no-sfx") || cfg.brand?.sfx === false,
    sfxVol: Number(cfg.brand?.sfxVolume ?? 1),
    lufs: Number(cfg.brand?.loudness ?? -14),
  });
  if (joins.length) console.log(`[video] ${joins.length} lan chuyen canh: ${joins.join(", ")}`);
  if (cues.length) console.log(`[am thanh] ${cues.length} tieng hieu ung: ${cues.join(", ")}`);
  console.log(`[am thanh] do to ${loud.before.toFixed(1)} -> ${loud.target} LUFS`);

  console.log(`\n=== Done ===\nWith audio : ${withAudio}\nSilent     : ${silent}`);
  console.log(`Total: ${(await durationSec(withAudio)).toFixed(2)}s (${scenes.length} scenes, ${W}x${H})`);
}

/** Entry point for a builder script. */
export function main(fmt) {
  run(fmt).catch((e) => { console.error("FAILED:", e); process.exit(1); });
}
