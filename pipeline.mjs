/**
 * Everything both builders share: helpers the scene styles use, then the run
 * itself - direct, check, TTS, render each scene in Chrome frame by frame,
 * join with transitions, mix and master the sound.
 *
 * A builder (build-styles.mjs for 9:16, build-16x9.mjs for 16:9) only owns
 * what differs by frame shape: its engine, its CSS and its scene styles. It
 * calls run() with those.
 */
